create or replace function public.student_shop(p_token text)
returns table(product_id text,category text,kind text,name text,description text,icon text,image text,price integer,owned boolean)
language plpgsql security definer set search_path=public stable as $$
declare v_student public.students%rowtype; v_student_id bigint;
begin
  v_student_id:=public.student_for_token(p_token);
  if v_student_id is null then raise exception '로그인이 만료됐어요. 다시 로그인해 주세요.'; end if;
  select * into v_student from public.students where id=v_student_id;
  return query select p.id,p.category,p.kind,p.name,p.description,p.icon,p.image,p.price,
    case when p.kind='wearable' then exists(select 1 from public.student_items si where si.student_id=v_student.id and si.item_id=p.item_id)
         else exists(select 1 from public.shop_orders o where o.student_id=v_student.id and o.product_id=p.id and o.status='pending') end
  from public.shop_products p where p.active and (p.stock is null or p.stock>0)
    and (p.gender is null or p.gender=v_student.gender)
    and (p.kind='wearable' or p.per_student_limit is null or (select count(*) from public.shop_orders o where o.student_id=v_student.id and o.product_id=p.id and o.status<>'cancelled')<p.per_student_limit)
  order by p.sort_order,p.price,p.name;
end; $$;
revoke all on function public.student_shop(text) from public;
grant execute on function public.student_shop(text) to anon,authenticated;

create or replace function public.student_buy_product(p_token text,p_product_id text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_student public.students%rowtype; v_student_id bigint; v_product public.shop_products%rowtype; v_order_id bigint;
begin
  v_student_id:=public.student_for_token(p_token);
  if v_student_id is null then raise exception '로그인이 만료됐어요. 다시 로그인해 주세요.'; end if;
  select * into v_student from public.students where id=v_student_id;
  select * into v_product from public.shop_products where id=p_product_id and active for update;
  if v_product.id is null then raise exception '판매하지 않는 상품이에요.'; end if;
  if v_product.gender is not null and v_product.gender<>v_student.gender then raise exception '내 캐릭터에게 맞지 않는 옷이에요.'; end if;
  if v_product.stock is not null and v_product.stock<1 then raise exception '상품이 품절됐어요.'; end if;
  if v_product.kind='wearable' and (v_product.item_id is null or v_product.item_id='') then raise exception '이 옷의 아이템 정보가 없어요.'; end if;
  if v_product.kind='wearable' and exists(select 1 from public.student_items where student_id=v_student.id and item_id=v_product.item_id) then raise exception '이미 가지고 있는 옷이에요.'; end if;
  if v_product.kind='coupon' and exists(select 1 from public.shop_orders where student_id=v_student.id and product_id=v_product.id and status='pending') then raise exception '이미 교환을 요청한 상품이에요.'; end if;
  if v_product.kind='coupon' and v_product.per_student_limit is not null and (select count(*) from public.shop_orders where student_id=v_student.id and product_id=v_product.id and status<>'cancelled')>=v_product.per_student_limit then raise exception '구매 가능 횟수를 모두 사용했어요.'; end if;
  update public.students set gold=gold-v_product.price where id=v_student.id and gold>=v_product.price;
  if not found then raise exception '골드가 부족해요.'; end if;
  if v_product.kind='wearable' then
    insert into public.student_items(student_id,item_id) values(v_student.id,v_product.item_id);
    if v_product.stock is not null then update public.shop_products set stock=stock-1 where id=v_product.id; end if;
    return jsonb_build_object('ok',true,'item_id',v_product.item_id,'price',v_product.price);
  end if;
  insert into public.shop_orders(student_id,product_id,price) values(v_student.id,v_product.id,v_product.price) returning id into v_order_id;
  if v_product.stock is not null then update public.shop_products set stock=stock-1 where id=v_product.id; end if;
  return jsonb_build_object('ok',true,'order_id',v_order_id,'price',v_product.price);
end; $$;
revoke all on function public.student_buy_product(text,text) from public;
grant execute on function public.student_buy_product(text,text) to anon,authenticated;

create or replace function public.teacher_shop_orders()
returns table(order_id bigint,student_number integer,student_name text,product_name text,product_icon text,price integer,created_at timestamptz)
language sql security definer set search_path=public stable as $$
  select o.id,s.student_number,s.nickname,p.name,p.icon,o.price,o.created_at
  from public.shop_orders o join public.students s on s.id=o.student_id join public.shop_products p on p.id=o.product_id
  where s.teacher_id=auth.uid() and o.status='pending' order by o.created_at;
$$;
revoke all on function public.teacher_shop_orders() from public;
grant execute on function public.teacher_shop_orders() to authenticated;

create or replace function public.teacher_resolve_shop_order(p_order_id bigint,p_status text)
returns void language plpgsql security definer set search_path=public as $$
declare v_order public.shop_orders%rowtype;
begin
  if p_status not in ('used','cancelled') then raise exception '처리 상태가 올바르지 않아요.'; end if;
  select o.* into v_order from public.shop_orders o join public.students s on s.id=o.student_id
  where o.id=p_order_id and o.status='pending' and s.teacher_id=auth.uid() for update of o;
  if v_order.id is null then raise exception '처리할 교환 요청을 찾지 못했어요.'; end if;
  update public.shop_orders set status=p_status,resolved_at=now(),resolved_by=auth.uid() where id=v_order.id;
  if p_status='cancelled' then
    update public.students set gold=gold+v_order.price where id=v_order.student_id;
    update public.shop_products set stock=stock+1 where id=v_order.product_id and stock is not null;
  end if;
end; $$;
revoke all on function public.teacher_resolve_shop_order(bigint,text) from public;
grant execute on function public.teacher_resolve_shop_order(bigint,text) to authenticated;

