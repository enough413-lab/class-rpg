create or replace function public.student_login_options()
returns table (student_number integer, login_id text, nickname text)
language sql security definer set search_path=public stable as $$
  select s.student_number,s.login_id,s.nickname from public.students s order by s.student_number;
$$;
revoke all on function public.student_login_options() from public;
grant execute on function public.student_login_options() to anon,authenticated;

create table if not exists public.shop_products (
  id text primary key,
  category text not null check(category in ('weapon','armor','top','bottom','shoes','misc')),
  kind text not null default 'coupon' check(kind in ('coupon','wearable')),
  name text not null, description text not null default '', icon text not null default '🎁', image text,
  price integer not null check(price>=0), active boolean not null default true,
  stock integer check(stock is null or stock>=0), per_student_limit integer check(per_student_limit is null or per_student_limit>0),
  item_id text, sort_order integer not null default 0, created_at timestamptz not null default now()
);
alter table public.shop_products add column if not exists gender text;
do $$ begin
  if not exists (select 1 from pg_constraint where conname='shop_products_gender_check') then
    alter table public.shop_products add constraint shop_products_gender_check check(gender in ('boy','girl') or gender is null);
  end if;
end $$;
create table if not exists public.shop_orders (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  product_id text not null references public.shop_products(id), price integer not null check(price>=0),
  status text not null default 'pending' check(status in ('pending','used','cancelled')),
  created_at timestamptz not null default now(), resolved_at timestamptz, resolved_by uuid references auth.users(id)
);
create index if not exists shop_orders_student_idx on public.shop_orders(student_id,status);
create index if not exists shop_orders_status_idx on public.shop_orders(status,created_at);
alter table public.shop_products enable row level security;
alter table public.shop_orders enable row level security;
revoke all on public.shop_products,public.shop_orders from anon,authenticated;

