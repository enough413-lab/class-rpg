create or replace function public.student_request_coupon_cancel(p_token text,p_order_id bigint,p_reason text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare sid bigint; o public.shop_orders%rowtype;
begin
 sid:=public.student_for_token(p_token);if sid is null then raise exception '로그인이 만료됐어요. 다시 로그인해 주세요.';end if;
 select * into o from public.shop_orders where id=p_order_id and student_id=sid for update;
 if not found then raise exception '내 교환권을 다시 확인해 주세요.';end if;
 if o.status<>'pending' then raise exception '이미 처리한 교환권에는 취소 요청을 보낼 수 없어요.';end if;
 if length(trim(coalesce(p_reason,''))) not between 1 and 200 then raise exception '취소 이유를 1~200자로 적어 주세요.';end if;
 insert into rpg_private.shop_cancel_requests(order_id,student_id,reason) values(o.id,sid,trim(p_reason)) on conflict(order_id) do nothing;
 return jsonb_build_object('ok',true,'order_id',o.id,'requested',true,'refunded',false);
end; $$;
revoke all on function public.student_request_coupon_cancel(text,bigint,text) from public;
grant execute on function public.student_request_coupon_cancel(text,bigint,text) to anon,authenticated;
