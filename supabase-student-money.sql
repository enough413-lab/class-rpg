create table if not exists rpg_private.student_gold_events (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public.students(id) on delete cascade,
 before_gold integer not null,after_gold integer not null,delta integer not null,
 kind text not null check(kind in ('opening','received','spent')),
 created_at timestamptz not null default clock_timestamp(),
 check(before_gold>=0 and after_gold>=0 and delta=after_gold-before_gold)
);
alter table rpg_private.student_gold_events enable row level security;
revoke all on rpg_private.student_gold_events from public,anon,authenticated;
create unique index if not exists student_gold_events_one_opening on rpg_private.student_gold_events(student_id) where kind='opening';
create index if not exists student_gold_events_owner_cursor on rpg_private.student_gold_events(student_id,id desc);
create or replace function rpg_private.observe_student_gold_change()
returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.gold=old.gold then return new;end if;
 insert into rpg_private.student_gold_events(student_id,before_gold,after_gold,delta,kind)
 values(new.id,old.gold,old.gold,0,'opening') on conflict(student_id) where kind='opening' do nothing;
 insert into rpg_private.student_gold_events(student_id,before_gold,after_gold,delta,kind)
 values(new.id,old.gold,new.gold,new.gold-old.gold,case when new.gold>old.gold then 'received' else 'spent' end);
 return new;
end; $$;
revoke all on function rpg_private.observe_student_gold_change() from public,anon,authenticated;
drop trigger if exists observe_student_gold_change on public.students;
create trigger observe_student_gold_change after update of gold on public.students
for each row execute function rpg_private.observe_student_gold_change();
create or replace function public.student_gold_history(p_token text,p_before_id bigint default null)
returns jsonb language plpgsql security definer stable set search_path='' as $$
declare sid bigint; entries jsonb; cursor_id bigint; balance integer; opening integer;
begin
 sid:=public.student_for_token(p_token);if sid is null then raise exception '로그인이 만료됐어요. 다시 로그인해 주세요.';end if;
 select gold into balance from public.students where id=sid;
 select after_gold into opening from rpg_private.student_gold_events where student_id=sid and kind='opening';
 select coalesce(jsonb_agg(to_jsonb(x) order by x.id desc),'[]'::jsonb),min(x.id) into entries,cursor_id
 from(select id,before_gold,after_gold,delta,kind,created_at from rpg_private.student_gold_events where student_id=sid and (p_before_id is null or id<p_before_id) order by id desc limit 30)x;
 return jsonb_build_object('entries',entries,'balance',balance,'opening_balance',coalesce(opening,balance),'history_starts_at_first_change',true,'next_before_id',cursor_id,'has_more',exists(select 1 from rpg_private.student_gold_events where student_id=sid and id<cursor_id));
end; $$;
revoke all on function public.student_gold_history(text,bigint) from public;
grant execute on function public.student_gold_history(text,bigint) to anon,authenticated;


