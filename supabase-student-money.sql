 order_id bigint primary key references public.shop_orders(id) on delete cascade,
 student_id bigint not null references public.students(id) on delete cascade,
 reason text not null check(length(reason) between 1 and 200),created_at timestamptz not null default now()
);
alter table rpg_private.shop_cancel_requests enable row level security;
revoke all on rpg_private.shop_cancel_requests from public,anon,authenticated;
