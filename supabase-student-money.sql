create index if not exists student_purchase_receipts_by_owner
on rpg_private.student_action_receipts(student_id,created_at desc,request_id desc) where action='shop_buy';
create or replace function public.student_purchase_receipts(p_token text,p_before_at timestamptz default null,p_before_request uuid default null)
returns jsonb language plpgsql security definer stable set search_path='' as $$
declare sid bigint; rows jsonb; last_row jsonb;
begin
  sid:=public.student_for_token(p_token);if sid is null then raise exception '로그인이 만료됐어요. 다시 로그인해 주세요.';end if;
  if (p_before_at is null)<>(p_before_request is null) then raise exception '영수증을 처음부터 다시 불러와 주세요.';end if;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc,x.request_id desc),'[]'::jsonb) into rows
  from (select r.request_id,r.created_at,(r.response->>'price')::integer as price,
        coalesce(p.name,i.name,'구매한 아이템') as name,o.product_id,r.response->>'item_id' as item_id,
        o.id as order_id,o.status,o.resolved_at
        from rpg_private.student_action_receipts r
        left join public.shop_orders o on o.id=(r.response->>'order_id')::bigint and o.student_id=sid
        left join public.shop_products p on p.id=o.product_id
        left join public.item_catalog i on i.id=r.response->>'item_id'
        where r.student_id=sid and r.action='shop_buy' and r.response->>'ok'='true'
        and jsonb_typeof(r.response->'price')='number'
        and (p_before_at is null or (r.created_at,r.request_id)<(p_before_at,p_before_request))
        order by r.created_at desc,r.request_id desc limit 30) x;
  last_row:=rows->(jsonb_array_length(rows)-1);
  return jsonb_build_object('receipts',rows,'next_before_at',last_row->'created_at','next_before_request',last_row->'request_id',
   'has_more',exists(select 1 from rpg_private.student_action_receipts r where r.student_id=sid and r.action='shop_buy' and (r.created_at,r.request_id)<((last_row->>'created_at')::timestamptz,(last_row->>'request_id')::uuid)));
end; $$;
revoke all on function public.student_purchase_receipts(text,timestamptz,uuid) from public;
grant execute on function public.student_purchase_receipts(text,timestamptz,uuid) to anon,authenticated;


